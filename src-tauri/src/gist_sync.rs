//! Fixed-origin Gist transport and Tabby Cloud Sync V1/V2 wire compatibility.
//! Credentials stay in a request's memory. No token, secret, or HTTP body is logged.
use aes::cipher::{block_padding::Pkcs7, BlockDecryptMut, KeyIvInit};
use aes_gcm::{aead::{Aead, KeyInit}, Aes256Gcm, Nonce};
use base64::{engine::general_purpose::STANDARD, Engine};
use futures_util::StreamExt;
use rand::RngCore;
use serde::{Deserialize, Serialize};
use serde_json::{json, Value};
use std::time::Duration;

const HEADER: &str = "/*This file is generated by Cloud Sync Settings Plugin - DO NOT MODIFY THIS FILE DIRECTLY OTHERWISE PLUGIN WILL NOT WORK PROPERLY*/\n";
const LEGACY_KEY: &[u8] = b"tp!&nc3^to8y7^3#4%2%&szufx!";
const LIMIT: usize = 2 * 1024 * 1024;
// GitHub serves large Gist files as truncated API entries. Keep a margin below
// its inline-content limit so every successful upload remains readable here.
const WIRE_LIMIT: usize = 900 * 1024;
const DEFAULT_FILE: &str = "tabby-sync-settings";

#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct GistRequest {
    pub operation: String,
    #[serde(default)] pub gist_id: String,
    #[serde(default)] pub token: String,
    #[serde(default)] pub proxy: String,
    #[serde(default)] pub filename: String,
    #[serde(default)] pub encryption_secret: String,
    #[serde(default)] pub expected_revision: String,
    #[serde(default)] pub document: Value,
}

#[derive(Default, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct GistResponse {
    pub gist_id: String,
    pub url: String,
    pub revision: String,
    pub public: bool,
    pub filename: String,
    pub format: String,
    pub document: Value,
}

fn id(value: &str) -> Result<String, String> {
    if !(5..=64).contains(&value.len()) || !value.bytes().all(|c| c.is_ascii_hexdigit()) {
        return Err("Gist ID 无效".into());
    }
    Ok(value.to_ascii_lowercase())
}
fn filename(value: &str) -> Result<String, String> {
    let value = if value.is_empty() { DEFAULT_FILE } else { value };
    if value.len() > 120 || value.contains(['/', '\\', '\r', '\n']) || value == "." || value == ".." {
        return Err("同步文件名无效".into());
    }
    Ok(value.into())
}
fn client(proxy: &str) -> Result<reqwest::Client, String> {
    let mut builder = reqwest::Client::builder().no_proxy().timeout(Duration::from_secs(35))
        .connect_timeout(Duration::from_secs(12)).redirect(reqwest::redirect::Policy::none())
        .user_agent("hurricaneTerm-machine-sync");
    if !proxy.trim().is_empty() {
        let url = reqwest::Url::parse(proxy.trim()).map_err(|_| "HTTP 代理地址无效")?;
        if !matches!(url.scheme(), "http" | "https") || url.host_str().is_none() || !url.username().is_empty()
            || url.password().is_some() || url.query().is_some() || url.fragment().is_some() || url.path() != "/" {
            return Err("代理须为不含凭证的 HTTP/HTTPS 地址与端口".into());
        }
        builder = builder.proxy(reqwest::Proxy::https(url.as_str()).map_err(|_| "HTTP 代理地址无效")?);
    }
    builder.build().map_err(|_| "无法初始化 GitHub HTTPS 客户端".into())
}
fn status_error(status: reqwest::StatusCode) -> String {
    match status.as_u16() {
        401 => "GitHub Token 无效或已过期".into(),
        403 => "GitHub 拒绝访问：检查 gist 权限或 API 额度".into(),
        404 => "Gist 不存在，或 Token 无权访问".into(),
        409 | 412 => "云端已发生变化，请重新读取并预览后再上传".into(),
        422 => "GitHub 未接受此 Gist 内容，请检查文件名与权限".into(),
        429 => "GitHub 请求过于频繁，请稍后重试".into(),
        _ => format!("GitHub 请求失败（HTTP {}）", status.as_u16()),
    }
}
async fn send(client: &reqwest::Client, req: &GistRequest, method: reqwest::Method, base: &str, path: &str, body: Option<Value>) -> Result<Value, String> {
    // path is constructed exclusively from validated hexadecimal IDs or /user.
    let mut request = client.request(method, format!("{base}{path}"))
        .bearer_auth(&req.token).header("Accept", "application/vnd.github+json")
        .header("X-GitHub-Api-Version", "2022-11-28");
    if let Some(body) = body { request = request.json(&body); }
    let response = request.send().await.map_err(|_| "无法连接 GitHub，请检查网络与 HTTP 代理")?;
    if !response.status().is_success() { return Err(status_error(response.status())); }
    if response.content_length().unwrap_or(0) > (LIMIT * 3) as u64 { return Err("Gist 响应过大（最多 6 MiB）".into()); }
    let mut data = Vec::new(); let mut stream = response.bytes_stream();
    while let Some(chunk) = stream.next().await {
        let chunk = chunk.map_err(|_| "GitHub 响应读取失败")?;
        if data.len() + chunk.len() > LIMIT * 3 { return Err("Gist 响应过大（最多 6 MiB）".into()); }
        data.extend_from_slice(&chunk);
    }
    serde_json::from_slice(&data).map_err(|_| "GitHub 响应格式无效".into())
}
fn scrypt_key(secret: &str, salt: &[u8]) -> Result<[u8; 32], String> {
    let params = scrypt::Params::new(14, 8, 1, 32).map_err(|_| "加密参数无效")?;
    let mut key = [0u8; 32];
    scrypt::scrypt(secret.as_bytes(), salt, &params, &mut key).map_err(|_| "密钥派生失败")?;
    Ok(key)
}
fn decode_field(value: &Value, field: &str, expected: Option<usize>) -> Result<Vec<u8>, String> {
    let bytes = STANDARD.decode(value[field].as_str().ok_or("Tabby V2 加密字段缺失")?)
        .map_err(|_| "Tabby V2 Base64 字段无效")?;
    if expected.is_some_and(|n| bytes.len() != n) || bytes.len() > LIMIT { return Err("Tabby V2 字段长度无效".into()); }
    Ok(bytes)
}
fn decrypt_v2(payload: &str, secret: &str) -> Result<String, String> {
    if secret.is_empty() { return Err("此 Gist 使用 Tabby V2 加密，请输入原配置加密密钥".into()); }
    let v: Value = serde_json::from_str(payload).map_err(|_| "Tabby V2 加密数据无效")?;
    if v["format"] != "tabby-sync" || v["version"] != 2 || v["algorithm"] != "aes-256-gcm" || v["kdf"] != "scrypt"
        || v["keyLength"] != 32 || v["cost"] != 16384 || v["blockSize"] != 8 || v["parallelization"] != 1 {
        return Err("不支持的 Tabby V2 加密参数".into());
    }
    let salt = decode_field(&v, "salt", Some(16))?; let iv = decode_field(&v, "iv", Some(12))?;
    let tag = decode_field(&v, "authTag", Some(16))?; let mut ciphertext = decode_field(&v, "ciphertext", None)?;
    ciphertext.extend_from_slice(&tag);
    let key = scrypt_key(secret, &salt)?;
    let plaintext = Aes256Gcm::new_from_slice(&key).map_err(|_| "加密密钥无效")?
        .decrypt(Nonce::from_slice(&iv), ciphertext.as_ref()).map_err(|_| "配置加密密钥不正确，或云端内容已损坏")?;
    String::from_utf8(plaintext).map_err(|_| "解密后的配置不是 UTF-8".into())
}
fn decrypt_v1(payload: &str) -> Result<String, String> {
    let bytes = STANDARD.decode(payload.trim()).map_err(|_| "Tabby V1 加密数据无效")?;
    if bytes.len() < 32 || &bytes[..8] != b"Salted__" { return Err("不是可识别的 Tabby V1 加密数据".into()); }
    let salt = &bytes[8..16]; let mut material = Vec::new(); let mut previous = Vec::new();
    while material.len() < 48 {
        let mut input = previous; input.extend_from_slice(LEGACY_KEY); input.extend_from_slice(salt);
        previous = md5::compute(input).0.to_vec(); material.extend_from_slice(&previous);
    }
    let mut buffer = bytes[16..].to_vec();
    let plaintext = cbc::Decryptor::<aes::Aes256>::new_from_slices(&material[..32], &material[32..48])
        .map_err(|_| "Tabby V1 密钥无效")?.decrypt_padded_mut::<Pkcs7>(&mut buffer).map_err(|_| "Tabby V1 解密失败")?;
    String::from_utf8(plaintext.to_vec()).map_err(|_| "解密后的配置不是 UTF-8".into())
}
fn decode_content(content: &str, secret: &str) -> Result<(Value, String), String> {
    if content.len() > LIMIT { return Err("配置文件过大（最多 2 MiB）".into()); }
    let content = content.trim_start_matches('\u{feff}').trim();
    let (plain, format) = if let Some(payload) = content.strip_prefix(HEADER.trim_end()) {
        let payload = payload.trim();
        if payload.starts_with('{') { (decrypt_v2(payload, secret)?, "tabby-v2") }
        else { (decrypt_v1(payload)?, "tabby-v1") }
    } else { (content.to_owned(), "tabby-plain") };
    if plain.len() > LIMIT { return Err("解密后的配置过大（最多 2 MiB）".into()); }
    let document: Value = serde_yaml::from_str(&plain).map_err(|_| "配置不是有效的 Tabby JSON/YAML")?;
    if !document.is_object() || !document["profiles"].is_array() { return Err("配置缺少 Tabby profiles 列表，不会覆盖此文件".into()); }
    Ok((document, format.into()))
}
fn encode_content(document: &Value, secret: &str) -> Result<String, String> {
    if secret.chars().count() < 12 { return Err("上传需要至少 12 字符的配置加密密钥".into()); }
    if !document.is_object() || !document["profiles"].is_array() { return Err("上传配置缺少 profiles 列表".into()); }
    let plain = serde_json::to_vec(document).map_err(|_| "配置序列化失败")?;
    if plain.len() > LIMIT { return Err("配置文件过大（最多 2 MiB）".into()); }
    let mut salt = [0u8; 16]; let mut iv = [0u8; 12];
    rand::thread_rng().fill_bytes(&mut salt); rand::thread_rng().fill_bytes(&mut iv);
    let key = scrypt_key(secret, &salt)?;
    let mut ciphertext = Aes256Gcm::new_from_slice(&key).map_err(|_| "加密密钥无效")?
        .encrypt(Nonce::from_slice(&iv), plain.as_ref()).map_err(|_| "配置加密失败")?;
    let tag = ciphertext.split_off(ciphertext.len() - 16);
    let envelope = json!({ "format": "tabby-sync", "version": 2, "algorithm": "aes-256-gcm", "kdf": "scrypt",
        "salt": STANDARD.encode(salt), "iv": STANDARD.encode(iv), "authTag": STANDARD.encode(tag), "ciphertext": STANDARD.encode(ciphertext),
        "keyLength": 32, "cost": 16384, "blockSize": 8, "parallelization": 1 });
    let content = format!("{HEADER}{envelope}");
    if content.len() > WIRE_LIMIT { return Err("加密后的配置超过 900 KiB，GitHub 可能截断；请减少机器配置后重试".into()); }
    Ok(content)
}
fn revision(gist: &Value) -> Result<String, String> {
    gist["history"][0]["version"].as_str().filter(|s| !s.is_empty()).map(str::to_owned).ok_or_else(|| "GitHub 未返回 Gist 版本，不能安全上传".into())
}
fn response(gist: &Value, file: &str) -> Result<GistResponse, String> {
    let gist_id = id(gist["id"].as_str().unwrap_or_default())?;
    Ok(GistResponse { url: format!("https://gist.github.com/{gist_id}"), gist_id, revision: revision(gist)?,
        public: gist["public"].as_bool().unwrap_or(true), filename: file.into(), ..Default::default() })
}
pub async fn gist_request(req: GistRequest) -> Result<GistResponse, String> {
    gist_request_inner(req, "https://api.github.com").await
}
// Private base argument allows local HTTP fixtures without exposing an arbitrary
// origin in the Tauri command or forwarding real tokens to redirected hosts.
async fn gist_request_inner(req: GistRequest, base: &str) -> Result<GistResponse, String> {
    if req.token.trim().is_empty() || req.token.len() > 4096 || req.token.contains(['\r', '\n']) { return Err("GitHub Token 无效".into()); }
    let file = filename(&req.filename)?; let client = client(&req.proxy)?;
    match req.operation.as_str() {
        "test" if req.gist_id.is_empty() => {
            send(&client, &req, reqwest::Method::GET, base, "/user", None).await?;
            Ok(GistResponse::default())
        }
        "read" | "test" | "write" => {
            let gist_id = id(&req.gist_id)?; let path = format!("/gists/{gist_id}");
            let gist = send(&client, &req, reqwest::Method::GET, base, &path, None).await?;
            let mut out = response(&gist, &file)?;
            if req.operation == "test" { return Ok(out); }
            let entry = &gist["files"][&file];
            if !entry.is_object() { return Err(format!("Gist 没有文件 {file}，请检查同步文件名；不会覆盖其他文件")); }
            if entry["truncated"].as_bool().unwrap_or(false) { return Err("GitHub 截断了此配置，文件过大；不会使用不完整内容".into()); }
            let content = entry["content"].as_str().ok_or("Gist 文件内容缺失")?.to_owned();
            if req.operation == "read" {
                let secret = req.encryption_secret;
                let (document, format) = tokio::task::spawn_blocking(move || decode_content(&content, &secret)).await.map_err(|_| "配置解密任务失败")??;
                out.document = document; out.format = format; return Ok(out);
            }
            if req.expected_revision.is_empty() || req.expected_revision != out.revision { return Err("云端已发生变化，请重新读取并预览后再上传".into()); }
            // Revalidate the existing file and secret. A wrong secret cannot replace it.
            let secret = req.encryption_secret.clone();
            tokio::task::spawn_blocking(move || decode_content(&content, &secret)).await.map_err(|_| "配置解密任务失败")??;
            let document = req.document.clone(); let secret = req.encryption_secret.clone();
            let content = tokio::task::spawn_blocking(move || encode_content(&document, &secret)).await.map_err(|_| "配置加密任务失败")??;
            let updated = send(&client, &req, reqwest::Method::PATCH, base, &path, Some(json!({ "files": { &file: { "content": content } } }))).await?;
            let mut result = response(&updated, &file)?; result.format = "tabby-v2".into(); Ok(result)
        }
        "create" => {
            let document = req.document.clone(); let secret = req.encryption_secret.clone();
            let content = tokio::task::spawn_blocking(move || encode_content(&document, &secret)).await.map_err(|_| "配置加密任务失败")??;
            let gist = send(&client, &req, reqwest::Method::POST, base, "/gists", Some(json!({ "public": false,
                "description": "Tabby-compatible hurricaneTerm machine profiles", "files": { &file: { "content": content } } }))).await?;
            let mut out = response(&gist, &file)?; out.format = "tabby-v2".into(); Ok(out)
        }
        _ => Err("不支持的 Gist 操作".into()),
    }
}

