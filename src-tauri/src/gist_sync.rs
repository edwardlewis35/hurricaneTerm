    fn server(responses: Vec<(u16, Value)>) -> (String, std::thread::JoinHandle<Vec<(String, Value)>>) {
        use std::io::{Read, Write};
        let listener = std::net::TcpListener::bind("127.0.0.1:0").unwrap();
        let base = format!("http://{}", listener.local_addr().unwrap());
        let thread = std::thread::spawn(move || {
            let mut requests = Vec::new();
            for (status, response) in responses {
                let (mut stream, _) = listener.accept().unwrap(); stream.set_read_timeout(Some(Duration::from_secs(10))).unwrap();
                let mut data = Vec::new(); let (header_end, content_length) = loop {
                    let mut block = [0u8; 4096]; let n = stream.read(&mut block).unwrap(); assert!(n > 0); data.extend_from_slice(&block[..n]);
                    if let Some(index) = data.windows(4).position(|w| w == b"\r\n\r\n") {
                        let headers = String::from_utf8_lossy(&data[..index]).to_lowercase();
                        assert!(headers.contains("authorization: bearer fixture-token-not-real"));
                        let length = headers.lines().find_map(|line| line.strip_prefix("content-length:")).map(|n| n.trim().parse::<usize>().unwrap()).unwrap_or(0);
                        break (index + 4, length);
                    }
                };
                while data.len() < header_end + content_length {
                    let mut block = [0u8; 4096]; let n = stream.read(&mut block).unwrap(); assert!(n > 0); data.extend_from_slice(&block[..n]);
                }
                let request_line = String::from_utf8_lossy(&data[..header_end]).lines().next().unwrap().to_owned();
                let body = if content_length == 0 { Value::Null } else { serde_json::from_slice(&data[header_end..header_end + content_length]).unwrap() };
                requests.push((request_line, body));
                let payload = response.to_string();
                write!(stream, "HTTP/1.1 {status} Test\r\nContent-Type: application/json\r\nContent-Length: {}\r\nConnection: close\r\n\r\n{payload}", payload.len()).unwrap();
            }
            requests
        });
        (base, thread)
    }
